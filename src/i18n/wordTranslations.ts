export function getTranslatedWord(word: string, lang: LanguageCode): string {
  if (lang === 'en') return word;
  const match = WORD_TRANSLATIONS[word];
  if (match && match[lang]) {
    return match[lang]!;
  }
  // Fallback to Spanish if available, else original word
  if (match && match.es) {
    return match.es;
  }
  return word;
}
